awk '
/fun SyncedLyricsView\(/ {
    print "@Composable"
    print "fun SyncedLyricsView(lyrics: String, currentPositionMs: Long, offsetMs: Long, onOffsetChange: ((Long) -> Unit)?, activeColor: Color, textColor: Color) {"
    print "    val parsedLyrics = remember(lyrics) { parseLrc(lyrics, 0L) }"
    print "    "
    print "    if (parsedLyrics.isEmpty()) {"
    print "        LazyColumn(modifier = Modifier.fillMaxWidth().fillMaxHeight(0.7f)) {"
    print "            item {"
    print "                Text("
    print "                    text = lyrics,"
    print "                    color = textColor,"
    print "                    style = MaterialTheme.typography.bodyMedium.copy(fontSize = 18.sp, lineHeight = 28.sp),"
    print "                    modifier = Modifier.padding(bottom = 32.dp)"
    print "                )"
    print "            }"
    print "        }"
    print "        return"
    print "    }"
    print "    "
    print "    val listState = rememberLazyListState()"
    print "    "
    print "    val currentIndex = remember(currentPositionMs, parsedLyrics, offsetMs) {"
    print "        parsedLyrics.indexOfLast { it.timeMs + offsetMs <= currentPositionMs }"
    print "    }"
    print "    "
    print "    LaunchedEffect(currentIndex) {"
    print "        if (currentIndex >= 0) {"
    print "            listState.animateScrollToItem(index = maxOf(0, currentIndex - 2))"
    print "        }"
    print "    }"
    print "    "
    print "    Column(modifier = Modifier.fillMaxWidth()) {"
    print "        if (onOffsetChange != null) {"
    print "            Row("
    print "                modifier = Modifier"
    print "                    .fillMaxWidth()"
    print "                    .padding(bottom = 8.dp),"
    print "                verticalAlignment = Alignment.CenterVertically,"
    print "                horizontalArrangement = Arrangement.End"
    print "            ) {"
    print "                IconButton(onClick = { onOffsetChange(offsetMs - 500L) }, modifier = Modifier.size(32.dp)) {"
    print "                    Text(\"-\", color = textColor, fontWeight = FontWeight.Bold, fontSize = 20.sp)"
    print "                }"
    print "                Text("
    print "                    text = \"${if (offsetMs >= 0) \"+\" else \"\"}${offsetMs / 1000f}s\","
    print "                    color = textColor,"
    print "                    fontSize = 14.sp,"
    print "                    fontWeight = FontWeight.Medium,"
    print "                    modifier = Modifier.padding(horizontal = 8.dp)"
    print "                )"
    print "                IconButton(onClick = { onOffsetChange(offsetMs + 500L) }, modifier = Modifier.size(32.dp)) {"
    print "                    Text(\"+\", color = textColor, fontWeight = FontWeight.Bold, fontSize = 20.sp)"
    print "                }"
    print "            }"
    print "        }"
    print "        LazyColumn("
    print "            state = listState,"
    print "            modifier = Modifier.fillMaxWidth().weight(1f),"
    print "            contentPadding = PaddingValues(vertical = 32.dp)"
    print "        ) {"
    print "            items(parsedLyrics.size) { index ->"
    print "                val line = parsedLyrics[index]"
    print "                val isActive = index == currentIndex"
    print "                "
    print "                val animatedAlpha by animateFloatAsState("
    print "                    targetValue = if (isActive) 1f else 0.4f,"
    print "                    animationSpec = tween(durationMillis = 150)"
    print "                )"
    print "                val animatedSize by animateFloatAsState("
    print "                    targetValue = if (isActive) 24f else 20f,"
    print "                    animationSpec = spring(dampingRatio = Spring.DampingRatioMediumBouncy, stiffness = Spring.StiffnessLow)"
    print "                )"
    print "                "
    print "                Text("
    print "                    text = line.text,"
    print "                    color = if (isActive) activeColor else textColor,"
    print "                    fontWeight = if (isActive) FontWeight.Bold else FontWeight.Medium,"
    print "                    fontSize = animatedSize.sp,"
    print "                    lineHeight = (animatedSize + 8).sp,"
    print "                    modifier = Modifier"
    print "                        .fillMaxWidth()"
    print "                        .alpha(animatedAlpha)"
    print "                        .padding(vertical = 8.dp)"
    print "                )"
    print "            }"
    print "        }"
    print "    }"
    print "}"
    skip_to = "^}"
    next
}
{
    if (skip_to != "") {
        if ($0 ~ skip_to) {
            skip_to = ""
        }
        next
    }
    print $0
}
' app/src/main/java/com/auradownloader/app/SyncedLyricsView.kt > tmp.kt && mv tmp.kt app/src/main/java/com/auradownloader/app/SyncedLyricsView.kt
